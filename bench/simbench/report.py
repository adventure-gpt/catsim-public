def load(out: Path) -> list:
    recs = []
    for p in sorted(Path(out).glob("**/results.jsonl")):
        for line in p.read_text(encoding="utf-8").splitlines():
            try:
                recs.append(json.loads(line))
            except ValueError:
                pass
    return recs


def latest(recs, key):
    d = {}
    for r in recs:
        d[key(r)] = r
    return d


def sim_sort(names):
    return sorted(names, key=lambda n: ORDER.index(n) if n in ORDER else len(ORDER))


def nice(n):
    return NAMES.get(n, n)


def fmt_k(x):
    return f"{x / 1e6:.2f}M" if x >= 1e6 else f"{x / 1e3:.0f}k"


def mline(m: dict) -> str:
    return f"{m['cpu']}, {m['threads']} threads, {m['ram_gb']:g} GB RAM, {m['os'].split(' (')[0]}"


class Notes:
    """Footnotes, numbered in order of first use; the same text gets the same number."""

    def __init__(self):
        self.texts = []

    def mark(self, text: str) -> str:
        if text not in self.texts:
            self.texts.append(text)
        return f"<sup>{self.texts.index(text) + 1}</sup>"

    def lines(self) -> list[str]:
        return [f"{i + 1}. {t}" for i, t in enumerate(self.texts)]


def acc_rows(recs):
    acc = [r for r in recs if r.get("kind") == "accuracy"]
    rl = [dict(r, level="rlpr", suite="rlpr") for r in recs if r.get("kind") == "rlpr"]
    return latest(acc + rl, lambda r: (r["sim"], r["level"]))


def cell(level: str, r: dict | None, peers: list, notes: Notes, main_when: str | None) -> str:
    """One summary cell: exact / pass (or the level's equivalent), with footnotes."""
    if r is None:
        return "not run"
    who = nice(r["sim"])
    if r.get("status") == "not supported":
        return "not supported" + notes.mark(f"{who}, {LEVELS[level][0]}: {r.get('why', 'its adapter cannot take this level')}.")
    if r.get("status") != "ok":
        return r.get("status", "not run") + notes.mark(f"{who}, {LEVELS[level][0]}: {r.get('why', '')}.")
    marks = ""
    if r.get("binding"):
        marks += notes.mark(f"{who}, {LEVELS[level][0]}: through {nice(r['binding'])} ({r.get('version', '')}), the "
                            "binding that runs this level.")
    if main_when and r.get("when") and r["when"][:10] != main_when[:10]:
        marks += notes.mark(f"{who}, {LEVELS[level][0]}: from the run of {r['when'].replace('T', ' ')}.")
    if level in ("A", "B", "Bp"):
        a = r["summary"]["all"]
        most = max((p["summary"]["all"]["body_ticks"] for p in peers if p.get("status") == "ok"), default=a["body_ticks"])
        if a["body_ticks"] < most or a.get("failed_segments"):
            marks += notes.mark(f"{who}, {LEVELS[level][0]}: scored on {a['body_ticks']:,} body-ticks of {most:,}"
                                + (f" ({a['failed_segments']:,} segments failed in its worker)" if a.get("failed_segments") else "") + ".")
        return f"{a['exact_body_ticks']:.2f}% / {a['segment_pass']:.2f}%{marks}"
    if level == "rlpr":
        a = r["results"]["segments_120"]["total"]
        return f"{a['pass_pct']:.2f}% / {a['mean_norm']:.2f}{marks}"
    s = r["summary"]
    if s.get("bodies_only"):
        marks += notes.mark(f"{who}, {LEVELS[level][0]}: the harness runs the match flow (kickoff starts and the countdown "
                            "hold, restarts after goals, respawns where the recording has them, each frame's ticks); "
                            "scored on bodies only, no boost or pads.")
    if s.get("failed"):
        marks += notes.mark(f"{who}, {LEVELS[level][0]}: {s['failed']} recordings failed in its worker.")
    e = (s.get("error_after_kickoff") or {}).get("5.0")
    return (f"{s['exact_to_the_end']}/{s['recordings']} games / {s['exact_pct']:.1f}% rows"
            + (f" / {e:.2f} at 5 s" if e is not None else "") + marks)


# One simulator, two bindings: the summary shows one column, the native worker's result where it has one and the
# other binding's where only that one runs the level (footnoted). The detail tables keep both.
SAME = {"catsim-py": "catsim"}


def summary_table(recs, notes: Notes) -> list[str]:
    acc = acc_rows(recs)
    for (s, lv), r in list(acc.items()):
        main = SAME.get(s)
        if main:
            have = acc.get((main, lv))
            if r.get("status") == "ok" and (have is None or have.get("status") != "ok"):
                acc[(main, lv)] = dict(r, binding=s)
            del acc[(s, lv)]
    sims_all = sim_sort({k[0] for k in acc})
    levels = [lv for lv in ("A", "B", "Bp", "rlpr", "C", "D") if any(k[1] == lv for k in acc)]
    if not levels:
        return []
    whens = Counter(r.get("when", "")[:10] for r in acc.values() if r.get("status") == "ok")
    main_when = whens.most_common(1)[0][0] if whens else None
    out = ["| given | " + " | ".join(nice(s) for s in sims_all) + " |", "|---|" + "---|" * len(sims_all)]
    for lv in levels:
        peers = [r for k, r in acc.items() if k[1] == lv]
        cells = [cell(lv, acc.get((s, lv)), peers, notes, main_when) for s in sims_all]
        out.append(f"| **{LEVELS[lv][0].split('. ')[0]}**: {LEVELS[lv][1]} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("Each cell: levels A and B, bit-exact body-ticks / segment pass; rlpr_metric, its pass rate / mean "
               "normalized error over 120-tick segments; levels C and D, games exact to the end / packet rows exact / the "
               "normalized error 5 s after each kickoff (0 is exact).")
    out.append("")
    return out
def charts(recs, out: Path) -> list[Path]:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("(charts skipped: pip install matplotlib)")
        return []
    made = []
    out.mkdir(parents=True, exist_ok=True)
    sp = [r for r in recs if r.get("kind") == "speed" and r.get("status") == "ok"]
    last = latest(sp, lambda r: (r["sim"], r["mode"], r["arenas"], r["threads"]))
    acc = latest([r for r in recs if r.get("kind") == "accuracy" and r.get("status") == "ok" and r.get("suite") == "full-state suite"],
                 lambda r: (r["sim"], r["level"]))
    for theme, colors, bg, ink, muted, grid in (("light", LIGHT, "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"),
                                               ("dark", DARK, "#1a1a19", "#f0efec", "#c3c2b7", "#3a3936")):
        def axes(title, ylabel):
            fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
            fig.patch.set_facecolor(bg)
            ax.set_facecolor(bg)
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            for side in ("left", "bottom"):
                ax.spines[side].set_color(grid)
            ax.tick_params(colors=muted, labelsize=9)
            ax.yaxis.grid(True, color=grid, linewidth=0.8)
            ax.set_axisbelow(True)
            ax.set_title(title, color=ink, fontsize=12, loc="left", pad=26)
            ax.set_ylabel(ylabel, color=muted, fontsize=9)
            return fig, ax

        def bars(ax, groups, series, value, label):
            w = 0.8 / max(len(series), 1)
            for k, s in enumerate(series):
                xs, ys = [], []
                for g, grp in enumerate(groups):
                    v = value(s, grp)
                    if v is not None:
                        xs.append(g - 0.4 + w * (k + 0.5))
                        ys.append(v)
                c = colors[ORDER.index(s) % len(colors)] if s in ORDER else colors[-1]
                ax.bar(xs, ys, w * 0.9, color=c, label=nice(s), edgecolor=bg, linewidth=1)
                for x, y in zip(xs, ys):
                    ax.text(x, y, label(y), ha="center", va="bottom", fontsize=7, color=muted)
            ax.set_xticks(range(len(groups)))
            top = ax.get_ylim()[1]
            ax.set_ylim(0, top * 1.08)
            leg = ax.legend(frameon=False, fontsize=8, ncol=min(len(series), 4), loc="lower left", bbox_to_anchor=(0, 1.0),
                            borderaxespad=0.2, handlelength=1.2)
            for t in leg.get_texts():
                t.set_color(ink)

        # CPU speed at the training-style load point (1024 arenas, all threads)
        cpu = [r for r in last.values() if r.get("device", "cpu") == "cpu" and r["arenas"] == 1024]
        if cpu:
            series = sim_sort({r["sim"] for r in cpu})
            modes = ["1v1", "2v2", "3v3"]
            m = cpu[0]["machine"]
            fig, ax = axes(f"CPU speed: 1,024 arenas, {cpu[0]['threads']} threads ({m['cpu'].split('@')[0].strip()})",
                           "million arena-ticks per second")
            get = lambda s, mode: next((r["arena_ticks_per_s"] / 1e6 for r in cpu if r["sim"] == s and r["mode"] == mode), None)
            bars(ax, modes, series, get, lambda y: f"{y:.2f}")
            ax.set_xticklabels(modes, color=ink)
            p = out / f"speed_cpu_{theme}.png"
            fig.tight_layout()
            fig.savefig(p, facecolor=bg)
            plt.close(fig)
            made.append(p)
        gpu = [r for r in last.values() if r.get("device") == "gpu"]
        if gpu:
            series = sim_sort({r["sim"] for r in gpu})
            sizes = sorted({r["arenas"] for r in gpu})
            for mode in ("1v1", "3v3"):
                rows = [r for r in gpu if r["mode"] == mode]
                if not rows:
                    continue
                m = rows[0]["machine"]
                fig, ax = axes(f"GPU speed, {mode} ({', '.join(x.split(',')[0] for x in m.get('gpus') or ['GPU'])})",
                               "million arena-ticks per second")
                get = lambda s, n: next((r["arena_ticks_per_s"] / 1e6 for r in rows if r["sim"] == s and r["arenas"] == n), None)
                bars(ax, [str(n) for n in sizes], series, lambda s, n: get(s, int(n)), lambda y: f"{y:.1f}")
                ax.set_xticklabels([f"{n:,} arenas" for n in sizes], color=ink)
                p = out / f"speed_gpu_{mode}_{theme}.png"
                fig.tight_layout()
                fig.savefig(p, facecolor=bg)
                plt.close(fig)
                made.append(p)
        if acc:
            levels = [lv for lv in ("A", "B") if any(k[1] == lv for k in acc)]
            series = sim_sort({k[0] for k in acc})
            fig, ax = axes("Accuracy on the full-state suite: bit-exact body-ticks", "% of body-ticks exact")
            get = lambda s, lv: acc[(s, lv)]["summary"]["all"]["exact_body_ticks"] if (s, lv) in acc else None
            bars(ax, levels, series, get, lambda y: f"{y:.1f}")
            ax.set_xticklabels([LEVELS[lv][0] for lv in levels], color=ink, fontsize=9)
            ax.set_ylim(0, 110)
            p = out / f"accuracy_{theme}.png"
            fig.tight_layout()
            fig.savefig(p, facecolor=bg)
            plt.close(fig)
