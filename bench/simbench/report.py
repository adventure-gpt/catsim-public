def markdown(sec: dict) -> str:
    """report.md, in the page's order: the accuracy table, the speed panels, then every detail."""
    text = ["# Rocket League simulator benchmark\n", sec["subtitle"] + "\n", "## Accuracy\n"] + sec["accuracy"]
