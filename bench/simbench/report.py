def load(out: Path) -> list:
    recs = []
    for p in sorted(Path(out).glob("**/results.jsonl")):
        for line in p.read_text(encoding="utf-8").splitlines():
            try:
                recs.append(json.loads(line))
            except ValueError:
                pass
    return recs


def latest(recs, key):
    d = {}
    for r in recs:
        d[key(r)] = r
    return d


def sim_sort(names):
    return sorted(names, key=lambda n: ORDER.index(n) if n in ORDER else len(ORDER))


def nice(n):
    return NAMES.get(n, n)


def fmt_k(x):
    return f"{x / 1e6:.2f}M" if x >= 1e6 else f"{x / 1e3:.0f}k"


def mline(m: dict) -> str:
    return f"{m['cpu']}, {m['threads']} threads, {m['ram_gb']:g} GB RAM, {m['os'].split(' (')[0]}"


class Notes:
    """Footnotes, numbered in order of first use; the same text gets the same number."""

    def __init__(self):
        self.texts = []

    def mark(self, text: str) -> str:
        if text not in self.texts:
            self.texts.append(text)
        return f"<sup>{self.texts.index(text) + 1}</sup>"

    def lines(self) -> list[str]:
        return [f"{i + 1}. {t}" for i, t in enumerate(self.texts)]


def acc_rows(recs):
    acc = [r for r in recs if r.get("kind") == "accuracy"]
    rl = [dict(r, level="rlpr", suite="rlpr") for r in recs if r.get("kind") == "rlpr"]
    return latest(acc + rl, lambda r: (r["sim"], r["level"]))


def clean(why: str) -> str:
    """A stored reason in today's words (older results named the benchmarks by letter)."""
    for a, b in (("level C:", ""), ("level D:", ""), ("level A:", ""), ("level B:", ""), ("level D tests", "these games test"),
                 ("handing it the draws is level C", "handing it the draws instead is the whole-games run with the spots given")):
        why = why.replace(a, b)
    return why.strip()


def cell(level: str, r: dict | None, peers: list, notes: Notes, main_when: str | None) -> str:
    """One summary cell: exact / pass (or the level's equivalent), with footnotes."""
    if r is None:
        return "not run"
    who = nice(r["sim"])
    if r.get("status") == "not supported":
        return "not supported" + notes.mark(f"{who}, {LEVELS[level][1]}: {clean(r.get('why', 'its adapter cannot take this start'))}.")
    if r.get("status") != "ok":
        return r.get("status", "not run") + notes.mark(f"{who}, {LEVELS[level][1]}: {clean(r.get('why', ''))}.")
    marks = ""
    if r.get("binding"):
        marks += notes.mark(f"{who}, {LEVELS[level][1]}: through {nice(r['binding'])} ({r.get('version', '')}), the "
                            "binding that runs this level.")
    if main_when and r.get("when") and r["when"][:10] != main_when[:10]:
        marks += notes.mark(f"{who}, {LEVELS[level][1]}: from the run of {r['when'].replace('T', ' ')}.")
    if level not in WHOLE and level != "rlpr":
        a = r["summary"]["all"]
        most = max((p["summary"]["all"]["body_ticks"] for p in peers if p.get("status") == "ok"), default=a["body_ticks"])
        if a["body_ticks"] < most or a.get("failed_segments"):
            marks += notes.mark(f"{who}, {LEVELS[level][1]}: scored on {a['body_ticks']:,} body-ticks of {most:,}"
                                + (f" ({a['failed_segments']:,} segments failed in its worker)" if a.get("failed_segments") else "") + ".")
        return f"{a['exact_body_ticks']:.2f}% / {a['segment_pass']:.2f}%{marks}"
    if level == "rlpr":
        a = r["results"]["segments_120"]["total"]
        return f"{a['pass_pct']:.2f}% / {a['mean_norm']:.2f}{marks}"
    s = r["summary"]
    if s.get("bodies_only"):
        marks += notes.mark(f"{who}, {LEVELS[level][1]}: the harness runs the match flow (kickoff starts and the countdown "
                            "hold, restarts after goals, respawns where the recording has them, each frame's ticks); "
                            "scored on bodies only, no boost or pads.")
    if s.get("failed"):
        marks += notes.mark(f"{who}, {LEVELS[level][1]}: {s['failed']} recordings failed in its worker.")
    e = (s.get("error_after_kickoff") or {}).get("5.0")
    return (f"{s['exact_to_the_end']}/{s['recordings']} games / {s['exact_pct']:.1f}% rows"
            + (f" / {e:.2f} at 5 s" if e is not None else "") + marks)


# One simulator, two bindings: the summary shows one column, the native worker's result where it has one and the
# other binding's where only that one runs the level (footnoted). The detail tables keep both.
SAME = {"catsim-py": "catsim"}


def merged_acc(recs) -> dict:
    acc = acc_rows(recs)
    for (s, lv), r in list(acc.items()):
        main = SAME.get(s)
        if main:
            have = acc.get((main, lv))
            if r.get("status") == "ok" and (have is None or have.get("status") != "ok"):
                acc[(main, lv)] = dict(r, binding=s, sim=main)
            del acc[(s, lv)]
    return acc


def drift_times(r: dict) -> list:
    """A whole-game result's time to the first drift per recording (a recording exact to the end counts its length)."""
    out = []
    for g in r.get("recordings") or []:
        if "error" in g:
            continue
        f = g.get("first_drift")
        out.append((g.get("name"), f["seconds"] if f and f.get("seconds") is not None else g.get("seconds"), f is None, g.get("seconds")))
    return out


def glance(recs) -> list[str]:
    """One plain line per benchmark, the same shape for every simulator, from the results."""
    acc = merged_acc(recs)
    out = []
    for lv in WHOLE:
        rows = [r for k, r in acc.items() if k[1] == lv and r.get("status") == "ok"]
        if not rows:
            continue
        n = max(r["summary"]["recordings"] for r in rows)
        if lv in ("D", "Df"):
            parts = [f"{nice(r['sim'])} models it: {r['summary']['exact_to_the_end']}/{r['summary']['recordings']} exact to the end"
                     for r in rows]
            out.append(f"- **{LEVELS[lv][0]}** ({n} recorded match{'es' if n != 1 else ''}): needs the game's random stream; " + "; ".join(parts) + ".")
            continue
        rows.sort(key=lambda r: (-r["summary"]["exact_to_the_end"], -(r["summary"].get("first_drift_s") or {}).get("median", 0)))
        parts = []
        for r in rows:
            sm = r["summary"]
            t = f"{nice(r['sim'])} {sm['exact_to_the_end']}/{sm['recordings']} exact to the end"
            if sm["exact_to_the_end"] < sm["recordings"] and lv == "Cf":
                t += f", {sm['exact_pct']:.1f}% of float rows exact"
            elif sm["exact_to_the_end"] < sm["recordings"] and sm.get("first_drift_s"):
                t += f", first drift after a median {sm['first_drift_s']['median']:.1f} s"
            parts.append(t)
        out.append(f"- **{LEVELS[lv][0]}** ({n} recorded match{'es' if n != 1 else ''}): " + "; ".join(parts) + ".")
    for lv in ("A", "B"):
        rows = [r for k, r in acc.items() if k[1] == lv and r.get("status") == "ok"]
        if not rows:
            continue
        rows.sort(key=lambda r: -r["summary"]["all"]["exact_body_ticks"])
        segs = max(r["summary"]["all"]["segments"] for r in rows)
        out.append(f"- **{LEVELS[lv][0]}** ({segs:,} segments of the full-state suite): "
                   + "; ".join(f"{nice(r['sim'])} {r['summary']['all']['exact_body_ticks']:.4f}% of body-ticks exact" for r in rows) + ".")
    sp = latest([r for r in recs if r.get("kind") == "speed" and r.get("status") == "ok"], lambda r: (r["sim"], r.get("mode"), r.get("arenas"), r.get("threads")))
    cpu = [r for r in sp.values() if r.get("device", "cpu") == "cpu" and r.get("arenas") == 1024 and r.get("mode") == "1v1"]
    if cpu:
        cpu.sort(key=lambda r: -r["arena_ticks_per_s"])
        line = (f"- **CPU speed** (1,024 arenas of 1v1 on {cpu[0]['threads']} threads, arena-ticks per second): "
                + "; ".join(f"{nice(r['sim'])} {fmt_k(r['arena_ticks_per_s'])}" for r in cpu))
        cat = next((r for r in cpu if r["sim"] == "catsim"), None)
        v3 = next((r for r in cpu if r["sim"] == "rocketsim-v3"), None)
        if cat and v3:
            k = cat["arena_ticks_per_s"] / v3["arena_ticks_per_s"]
            line += f". catSim runs at {k:.2f} times RocketSim v3's speed" + (" (about half)" if 0.4 <= k <= 0.6 else "")
        out.append(line + ".")
    gpu = [r for r in sp.values() if r.get("device") == "gpu" and r.get("mode") == "1v1"]
    if gpu:
        n = max(r["arenas"] for r in gpu)
        gpu = sorted((r for r in gpu if r["arenas"] == n), key=lambda r: -r["arena_ticks_per_s"])
        out.append(f"- **GPU speed** ({n:,} arenas of 1v1, arena-ticks per second): "
                   + "; ".join(f"{nice(r['sim'])} {fmt_k(r['arena_ticks_per_s'])}" for r in gpu) + ".")
    return out + ([""] if out else [])


def summary_table(recs, notes: Notes) -> list[str]:
    acc = merged_acc(recs)
    sims_all = sim_sort({k[0] for k in acc})
    levels = [lv for lv in ORDER_LEVELS if any(k[1] == lv for k in acc)]
    if not levels:
        return []
    whens = Counter(r.get("when", "")[:10] for r in acc.values() if r.get("status") == "ok")
    main_when = whens.most_common(1)[0][0] if whens else None
    out = ["| benchmark | " + " | ".join(nice(s) for s in sims_all) + " |", "|---|" + "---|" * len(sims_all)]
    for lv in levels:
        peers = [r for k, r in acc.items() if k[1] == lv]
        cells = [cell(lv, acc.get((s, lv)), peers, notes, main_when) for s in sims_all]
        out.append(f"| {LEVELS[lv][0]} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("The whole games come first: there the simulator runs each match on its own from the first kickoff, with "
               "nothing reloaded until the end, which makes them the strictest test.")
    out.append("")
    out.append("Each cell: whole games, games exact to the end / packet rows exact / the normalized error 5 s after each "
               "kickoff (0 is exact); the segment benchmarks, bit-exact body-ticks / segment pass; rlpr_metric, its pass "
               "rate / mean normalized error over 120-tick segments.")
    out.append("")
    return out
def charts(recs, out: Path) -> list[Path]:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("(charts skipped: pip install matplotlib)")
        return []
    made = []
    out.mkdir(parents=True, exist_ok=True)
    sp = [r for r in recs if r.get("kind") == "speed" and r.get("status") == "ok"]
    last = latest(sp, lambda r: (r["sim"], r["mode"], r["arenas"], r["threads"]))
    acc = latest([r for r in recs if r.get("kind") == "accuracy" and r.get("status") == "ok" and r.get("suite") == "full-state suite"],
                 lambda r: (r["sim"], r["level"]))
    for theme, colors, bg, ink, muted, grid in (("light", LIGHT, "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"),
                                               ("dark", DARK, "#1a1a19", "#f0efec", "#c3c2b7", "#3a3936")):
        def axes(title, ylabel):
            fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
            fig.patch.set_facecolor(bg)
            ax.set_facecolor(bg)
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            for side in ("left", "bottom"):
                ax.spines[side].set_color(grid)
            ax.tick_params(colors=muted, labelsize=9)
            ax.yaxis.grid(True, color=grid, linewidth=0.8)
            ax.set_axisbelow(True)
            ax.set_title(title, color=ink, fontsize=12, loc="left", pad=26)
            ax.set_ylabel(ylabel, color=muted, fontsize=9)
            return fig, ax

        def bars(ax, groups, series, value, label):
            w = 0.8 / max(len(series), 1)
            for k, s in enumerate(series):
                xs, ys = [], []
                for g, grp in enumerate(groups):
                    v = value(s, grp)
                    if v is not None:
                        xs.append(g - 0.4 + w * (k + 0.5))
                        ys.append(v)
                c = colors[ORDER.index(s) % len(colors)] if s in ORDER else colors[-1]
                ax.bar(xs, ys, w * 0.9, color=c, label=nice(s), edgecolor=bg, linewidth=1)
                for x, y in zip(xs, ys):
                    ax.text(x, y, label(y), ha="center", va="bottom", fontsize=7, color=muted)
            ax.set_xticks(range(len(groups)))
            top = ax.get_ylim()[1]
            ax.set_ylim(0, top * 1.08)
            leg = ax.legend(frameon=False, fontsize=8, ncol=min(len(series), 4), loc="lower left", bbox_to_anchor=(0, 1.0),
                            borderaxespad=0.2, handlelength=1.2)
            for t in leg.get_texts():
                t.set_color(ink)

        # the time to the first drift in whole games: each recording a dot, each simulator's median a bar
        whole = merged_acc(recs)
        rows = sorted((r for k, r in whole.items() if k[1] == "C" and r.get("status") == "ok"), key=lambda r: ORDER.index(r["sim"]) if r["sim"] in ORDER else 99)
        if rows:
            fig, ax = plt.subplots(figsize=(8, 0.9 + 0.62 * len(rows)), dpi=150)
            fig.patch.set_facecolor(bg)
            ax.set_facecolor(bg)
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            for side in ("left", "bottom"):
                ax.spines[side].set_color(grid)
            ax.tick_params(colors=muted, labelsize=9)
            ax.xaxis.grid(True, color=grid, linewidth=0.8)
            ax.set_axisbelow(True)
            for y, r in enumerate(rows):
                c = colors[ORDER.index(r["sim"]) % len(colors)] if r["sim"] in ORDER else colors[-1]
                pts = [t for t in drift_times(r) if t[1]]
                if not pts:
                    continue
                med = sorted(t[1] for t in pts)[len(pts) // 2]
                ax.barh(y, med, height=0.36, color=c, alpha=0.35, edgecolor=bg, linewidth=1)
                ax.scatter([t[1] for t in pts], [y] * len(pts), s=18, color=c, edgecolors=bg, linewidths=0.8, zorder=3)
                done = sum(t[2] for t in pts)
                ax.text(max(t[1] for t in pts) * 1.15, y, f"{done}/{len(pts)} exact to the end" if done else f"median {med:.1f} s",
                        va="center", fontsize=8, color=ink)
            ax.set_yticks(range(len(rows)))
            ax.set_yticklabels([nice(r["sim"]) for r in rows], color=ink, fontsize=9)
            ax.invert_yaxis()
            ax.set_xscale("log")
            lo = min((t[1] for r in rows for t in drift_times(r) if t[1]), default=0.1)
            hi = max((t[1] for r in rows for t in drift_times(r) if t[1]), default=600)
            ax.set_xlim(max(lo / 2, 0.005), hi * 6)
            ax.set_xlabel("seconds into the game (log scale); a game exact to the end is drawn at its length", color=muted, fontsize=9)
            ax.set_title("Time to the first drift in whole games", color=ink, fontsize=12, loc="left", pad=12)
            p = out / f"drift_{theme}.png"
            fig.tight_layout()
            fig.savefig(p, facecolor=bg)
            plt.close(fig)
            made.append(p)

        # CPU speed at the training-style load point (1024 arenas, all threads)
        cpu = [r for r in last.values() if r.get("device", "cpu") == "cpu" and r["arenas"] == 1024]
        if cpu:
            series = sim_sort({r["sim"] for r in cpu})
            modes = ["1v1", "2v2", "3v3"]
            m = cpu[0]["machine"]
            fig, ax = axes(f"CPU speed: 1,024 arenas, {cpu[0]['threads']} threads ({m['cpu'].split('@')[0].strip()})",
                           "million arena-ticks per second")
            get = lambda s, mode: next((r["arena_ticks_per_s"] / 1e6 for r in cpu if r["sim"] == s and r["mode"] == mode), None)
            bars(ax, modes, series, get, lambda y: f"{y:.2f}")
            ax.set_xticklabels(modes, color=ink)
            p = out / f"speed_cpu_{theme}.png"
            fig.tight_layout()
            fig.savefig(p, facecolor=bg)
            plt.close(fig)
            made.append(p)
        gpu = [r for r in last.values() if r.get("device") == "gpu"]
        if gpu:
            series = sim_sort({r["sim"] for r in gpu})
            sizes = sorted({r["arenas"] for r in gpu})
            for mode in ("1v1", "3v3"):
                rows = [r for r in gpu if r["mode"] == mode]
                if not rows:
                    continue
                m = rows[0]["machine"]
                fig, ax = axes(f"GPU speed, {mode} ({', '.join(x.split(',')[0] for x in m.get('gpus') or ['GPU'])})",
                               "million arena-ticks per second")
                get = lambda s, n: next((r["arena_ticks_per_s"] / 1e6 for r in rows if r["sim"] == s and r["arenas"] == n), None)
                bars(ax, [str(n) for n in sizes], series, lambda s, n: get(s, int(n)), lambda y: f"{y:.1f}")
                ax.set_xticklabels([f"{n:,} arenas" for n in sizes], color=ink)
                p = out / f"speed_gpu_{mode}_{theme}.png"
                fig.tight_layout()
                fig.savefig(p, facecolor=bg)
                plt.close(fig)
                made.append(p)
        if acc:
            levels = [lv for lv in ("A", "B") if any(k[1] == lv for k in acc)]
            series = sim_sort({k[0] for k in acc})
            fig, ax = axes("Accuracy on the full-state suite: bit-exact body-ticks", "% of body-ticks exact")
            get = lambda s, lv: acc[(s, lv)]["summary"]["all"]["exact_body_ticks"] if (s, lv) in acc else None
            bars(ax, levels, series, get, lambda y: f"{y:.1f}")
            ax.set_xticklabels([LEVELS[lv][1].capitalize() + " given" for lv in levels], color=ink, fontsize=9)
            ax.set_ylim(0, 110)
            p = out / f"accuracy_{theme}.png"
            fig.tight_layout()
            fig.savefig(p, facecolor=bg)
            plt.close(fig)
            made.append(p)
    return made


BUSY_CORES = 0.25           # other processes' CPU, in cores, above which a timed round gets a footnote


def busy_note(r: dict, notes) -> str:
    """A footnote when something outside the harness was busy during one of the row's rounds (or nothing measured)."""
    ld = r.get("load")
    if ld is None:
        return notes.mark("Machine load during the rounds not recorded (results from before simbench measured it).")
    cores = [x.get("other_cores") for x in ld if x.get("other_cores") is not None]
    gpu = sorted({g for x in ld for g in x.get("other_gpu_processes") or []})
    out = ""
    if not cores:
        out += notes.mark("Machine load during the rounds not measured (simbench measures it on Linux).")
    if cores and max(cores) > BUSY_CORES:
        out += notes.mark(f"{nice(r['sim'])}, {r['mode']}, {r['arenas']:,} arenas: other processes used up to "
                          f"{max(cores):.2f} cores during a round.")
    if gpu:
        out += notes.mark(f"{nice(r['sim'])}, {r['mode']}, {r['arenas']:,} arenas: other processes on the GPU: {', '.join(gpu)}.")
    return out


def speed_tables(recs, notes=None) -> list[str]:
    notes = notes or Notes()
    sp = [r for r in recs if r.get("kind") == "speed"]
    if not sp:
        return []
    out = []
    last = latest(sp, lambda r: (r["sim"], r.get("mode"), r.get("arenas"), r.get("threads")))
    for device in ("cpu", "gpu"):
        rows = [r for r in last.values() if r.get("device", "cpu") == device and r.get("mode")]
        if not rows:
            continue
        sims_here = sim_sort({r["sim"] for r in rows})
        m = next((r["machine"] for r in rows if r.get("status") == "ok"), rows[0]["machine"])
        hw = (", ".join(m.get("gpus") or []) or "GPU") if device == "gpu" else f"{m['cpu']}, {m['threads']} threads"
        out.append(f"### Speed, {device.upper()} simulators ({hw}; {m['os'].split(' (')[0]})\n")
        out.append("Arena-ticks per second, the median of the rounds (their spread in brackets). Identical work for every "
                   "simulator: the same start states and controls, 8 ticks per decision, every body read each decision."
                   + (" CPU and GPU simulators are never in one table." if device == "gpu" else "") + "\n")
        configs = sorted({(r["mode"], r["arenas"], r["threads"]) for r in rows}, key=lambda c: (c[0], c[1], c[2]))
        out.append("| mode | arenas | threads | " + " | ".join(nice(s) for s in sims_here) + " |")
        out.append("|---|---:|---:|" + "---:|" * len(sims_here))
        for mode, arenas, threads in configs:
            cells = []
            for s in sims_here:
                r = last.get((s, mode, arenas, threads))
                if r is None:
                    cells.append("-")
                elif r.get("status") == "ok":
                    cells.append(f"{fmt_k(r['arena_ticks_per_s'])} ({fmt_k(r['min'])}-{fmt_k(r['max'])})" + busy_note(r, notes))
                else:
                    cells.append(r.get("status", "not run"))
            out.append(f"| {mode} | {arenas:,} | {threads if device == 'cpu' else '-'} | " + " | ".join(cells) + " |")
        out.append("")
    not_run = latest([r for r in sp if r.get("status") == "not run"], lambda r: r["sim"])
    if not_run:
        out.append("Not run here: " + "; ".join(f"{nice(r['sim'])} ({r.get('why', '')})" for r in not_run.values()) + "\n")
    if notes.texts:
        out += notes.lines() + [""]
    return out


def detail_tables(recs) -> list[str]:
    acc = acc_rows(recs)
    out = []
    for level in [lv for lv in ORDER_LEVELS if lv != "rlpr"]:
        rs = sorted((r for k, r in acc.items() if k[1] == level), key=lambda r: ORDER.index(r["sim"]) if r["sim"] in ORDER else 99)
        if not rs:
            continue
        title, _, given = LEVELS[level]
        suite = rs[0].get("suite", "")
        out.append(f"### {title}\n")
        out.append(f"On {suite}.  ")
        out.append(f"Given: {given}.  ")
        if level in WHOLE:
            out.append("Scored: every compared packet row to the end of the recording (positions, velocities, rotation, as "
                       "the game rounds them; boost and pads too when the simulator runs the match itself), the time to the "
                       "first drift, and the full-state suite's normalized error 1, 5 and 30 s after each kickoff.\n")
            out.append("| simulator | match flow | recordings | exact to the end | packet rows exact | first drift: median (range) "
                       "| error 1 s / 5 s / 30 s |")
            out.append("|---|---|---:|---:|---:|---|---|")
            for r in rs:
                if r.get("status") != "ok":
                    out.append(f"| {nice(r['sim'])} | {r.get('status')}: {r.get('why', '')} | | | | | |")
                    continue
                s = r["summary"]
                d = s.get("first_drift_s") or {}
                e = s.get("error_after_kickoff") or {}
                f = lambda x: "-" if x is None else f"{x:.3f}"
                out.append(f"| {nice(r['sim'])} | {'the harness' if s.get('bodies_only') else 'its own'} | {s['recordings']} | "
                           f"{s['exact_to_the_end']} | {s['exact_rows']:,} of {s['compared_rows']:,} ({s['exact_pct']:.3f}%) | "
                           + (f"{d['median']:.1f} s ({d['min']:.1f}-{d['max']:.1f})" if d else "-")
                           + f" | {f(e.get('1.0'))} / {f(e.get('5.0'))} / {f(e.get('30.0'))} |")
            for r in rs:
                if r.get("status") == "ok" and r.get("assists"):
                    out.append(f"\nAssists for {nice(r['sim'])}: " + "; ".join(r["assists"]) + ".")
        else:
            out.append(f"Scored: {SUITE_SCORED}.\n")
            out.append("| simulator | exact body-ticks | exact segments | segment pass | mean error k1 / k30 / k120 | body-ticks | segments |")
            out.append("|---|---:|---:|---:|---|---:|---:|")
            for r in rs:
                if r.get("status") != "ok":
                    out.append(f"| {nice(r['sim'])} | {r.get('status')}: {r.get('why', '')} | | | | | |")
                    continue
                s = r["summary"]["all"]
                me = s["mean_error"]
                out.append(f"| {nice(r['sim'])} | {s['exact_body_ticks']:.4f}% | {s['exact_segments']:.3f}% | {s['segment_pass']:.3f}% | "
                           f"{me['1']:.4f} / {me['30']:.4f} / {me['120']:.4f} | {s['body_ticks']:,} | {s['segments']:,} |")
            splits = sorted({k for r in rs if r.get("status") == "ok" for k in r["summary"] if k != "all"})
            if splits:
                out.append("\nExact body-ticks by the suite's splits:\n")
                ok = [r for r in rs if r.get("status") == "ok"]
                out.append("| split | " + " | ".join(nice(r["sim"]) for r in ok) + " |")
                out.append("|---|" + "---:|" * len(ok))
                for sp in splits:
                    out.append(f"| {sp} | " + " | ".join(f"{r['summary'][sp]['exact_body_ticks']:.3f}%" if sp in r["summary"] else "-" for r in ok) + " |")
        out.append("")
    rl = sorted((r for k, r in acc.items() if k[1] == "rlpr"), key=lambda r: ORDER.index(r["sim"]) if r["sim"] in ORDER else 99)
    if rl:
        out += [f"### {LEVELS['rlpr'][0]}\n",
                f"Given: {LEVELS['rlpr'][2]}; or one tick from every record (one-tick).  Scored: RocketSim's own normalized "
                "error per car-tick, its own tolerances (pass = error under 1).\n",
                "| simulator | 120-tick pass | 120-tick mean norm | one-tick pass | one-tick mean norm | car-ticks |",
                "|---|---:|---:|---:|---:|---:|"]
        for r in rl:
            if r.get("status") != "ok":
                out.append(f"| {nice(r['sim'])} | {r.get('status')}: {r.get('why', '')} | | | | |")
                continue
            a, b = r["results"]["segments_120"]["total"], r["results"]["one_tick"]["total"]
            out.append(f"| {nice(r['sim'])} | {a['pass_pct']:.3f}% | {a['mean_norm']:.4f} | {b['pass_pct']:.3f}% | {b['mean_norm']:.4f} | {a['support']:,} |")
        out.append("")
    return out


def adapters_section(recs) -> list[str]:
    """Each simulator once: its exact version, what its adapter runs, and the adapter's choices."""
    by = {}
    for r in recs:
        if r.get("sim"):
            by.setdefault(r["sim"], []).append(r)
    out = []
    for s in sim_sort(by):
        rs = by[s]
        vs = Counter(r.get("version") for r in rs if r.get("version") and r.get("version") != "?")
        v = vs.most_common(1)[0][0] if vs else "version not reported"
        about = next((r.get("about") for r in reversed(rs) if r.get("about")), "")
        ch = next((r.get("choices") for r in reversed(rs) if r.get("choices")), [])
        out.append(f"- **{nice(s)}**: {v}. {about}" + (". " if about and not about.endswith(".") else " ")
                   + ("Its adapter: " + "; ".join(ch) + "." if ch else ""))
    return out + [""]


def machines(recs) -> list[str]:
    seen = {}
    for r in recs:
        if r.get("machine"):
            m = r["machine"]
            seen.setdefault(json.dumps(m, sort_keys=True), set()).add(r.get("bench") or r.get("kind"))
    out = []
    for k, benches in seen.items():
        m = json.loads(k)
        out.append(f"- {mline(m)}" + (f"; {', '.join(m['gpus'])}" if m.get("gpus") else "")
                   + (f" ({', '.join(sorted(b for b in benches if b))})" if len(seen) > 1 else ""))
    return out


def build(recs, charts_rel: str | None = None, chart_files=()) -> dict:
    """The report's sections as markdown lines: summary, speed, details, adapters, machines."""
    notes = Notes()
    summary = summary_table(recs, notes)
    summary += [f"{n}" for n in notes.lines()] + ([""] if notes.texts else [])
    pics = []
    if charts_rel is not None:
        names = sorted({Path(c).name.rsplit("_", 1)[0] for c in chart_files}, key=lambda b: (b != "drift", b))
        for base in names:
            pics.append(f'<picture><source media="(prefers-color-scheme: dark)" srcset="{charts_rel}/{base}_dark.png">'
                        f'<img alt="{base.replace("_", " ")}" src="{charts_rel}/{base}_light.png" width="720"></picture>')
            pics.append("")
    return {"glance": glance(recs), "summary": summary, "charts": pics, "speed": speed_tables(recs), "details": detail_tables(recs),
            "adapters": adapters_section(recs), "machines": machines(recs)}


def markdown(sec: dict) -> str:
    text = ["# Benchmark results\n", "## At a glance\n"] + sec["glance"] + sec["charts"][:2] + ["## Summary\n"] + sec["summary"]
    text += sec["charts"][2:] + ["Machine:\n"] + sec["machines"] + [""]
    text += ["## Speed\n"] + sec["speed"] + ["## Details\n"] + sec["details"] + ["## The simulators and their adapters\n"] + sec["adapters"]
    return "\n".join(text)


def _inline(s: str) -> str:
    s = html.escape(s, quote=False).replace("&lt;sup&gt;", "<sup>").replace("&lt;/sup&gt;", "</sup>")
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    return s


def to_html(md: str, images: dict) -> str:
    """The markdown above (headings, tables, lists, paragraphs, pictures) as one page with its charts inside."""
    body, table, lst = [], None, False
    for line in md.splitlines() + [""]:
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if table is None:
                table = ["<table><thead><tr>" + "".join(f"<th>{_inline(c)}</th>" for c in cells) + "</tr></thead><tbody>"]
            elif all(re.fullmatch(r":?-+:?", c) for c in cells):
                pass
            else:
                table.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in cells) + "</tr>")
            continue
        if table is not None:
            body.append("".join(table) + "</tbody></table>")
            table = None
        if line.startswith("- "):
            if not lst:
                body.append("<ul>")
                lst = True
            body.append(f"<li>{_inline(line[2:])}</li>")
            continue
        if lst:
            body.append("</ul>")
            lst = False
        if line.startswith("<picture>"):
            m = re.search(r'srcset="[^"]*/([^"/]+)_dark\.png".*alt="([^"]*)"', line)
            if m and m.group(1) in images:
                light, dark = images[m.group(1)]
                body.append(f'<picture><source media="(prefers-color-scheme: dark)" srcset="data:image/png;base64,{dark}">'
                            f'<img alt="{m.group(2)}" src="data:image/png;base64,{light}"></picture>')
            continue
        h = re.match(r"(#+) (.*)", line)
        if h:
            n = len(h.group(1))
            body.append(f"<h{n}>{_inline(h.group(2))}</h{n}>")
        elif re.match(r"\d+\. ", line):
            body.append(f'<p class="note">{_inline(line)}</p>')
        elif line.strip():
            body.append(f"<p>{_inline(line)}</p>")
    css = """
:root{--bg:#fcfcfb;--ink:#0b0b0b;--muted:#52514e;--rule:#e4e3df;--head:#f3f2ef}
@media (prefers-color-scheme: dark){:root{--bg:#1a1a19;--ink:#f0efec;--muted:#c3c2b7;--rule:#3a3936;--head:#242422}}
body{background:var(--bg);color:var(--ink);font:15px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif;margin:0 auto;max-width:1100px;padding:24px 16px}
h1{font-size:26px;margin:0 0 8px}h2{font-size:20px;margin:32px 0 8px}h3{font-size:16px;margin:24px 0 6px}
p,li{color:var(--ink)}.note{color:var(--muted);font-size:13px;margin:2px 0}
table{border-collapse:collapse;margin:8px 0 12px;font-size:13px;display:block;overflow-x:auto;max-width:100%}
th,td{border-bottom:1px solid var(--rule);padding:5px 9px;text-align:left;vertical-align:top}
th{background:var(--head);font-weight:600}td:not(:first-child){font-variant-numeric:tabular-nums}
img{max-width:100%;height:auto}code{font-size:13px}sup{color:var(--muted)}
"""
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, "
            "initial-scale=1\"><title>Simulator benchmark</title><style>" + css + "</style></head><body>"
            + "\n".join(body) + "</body></html>")


def fill_doc(doc: Path, sec: dict, charts_dir: Path, made) -> None:
    """Replace docs/BENCHMARKS.md's generated sections (between its simbench markers) and copy the charts beside it."""
    text = doc.read_text(encoding="utf-8")
    dest = doc.parent / "bench"
    dest.mkdir(exist_ok=True)
    for c in made:
        shutil.copy2(c, dest / Path(c).name)
    rel = build_rel = "bench"
    pics = [l.replace("charts/", f"{rel}/") for l in sec["charts"]]
    parts = {"summary": ["## At a glance\n"] + sec["glance"] + pics[:2] + ["## Summary\n"] + sec["summary"] + pics[2:]
                        + ["", "Machine:", ""] + sec["machines"],
             "details": ["## Speed\n"] + sec["speed"] + ["## Every benchmark in detail\n"] + sec["details"]
                        + ["## The simulators and their adapters\n"] + sec["adapters"]}
    for name, lines in parts.items():
        a, b = GEN.format(name), END.format(name)
        block = a + "\n\n" + "\n".join(lines).strip() + "\n\n" + b
        if a in text and b in text:
            text = text[:text.index(a)] + block + text[text.index(b) + len(b):]
        elif "{{" + name.upper() + "}}" in text:
            text = text.replace("{{" + name.upper() + "}}", block)
        else:
            raise SystemExit(f"{doc} has no {name} section to fill ({a})")
    doc.write_text(text, encoding="utf-8", newline="\n")
    print(f"filled: {doc} (charts in {dest})")
    readme = doc.parent.parent / "README.md"
    a, b = GEN.format("glance"), END.format("glance")
    if readme.is_file():
        t = readme.read_text(encoding="utf-8")
        if a in t and b in t:
            lines = [l for l in sec["glance"] if l.startswith("- **Whole games")]
            block = a + "\n\n" + "\n".join(lines) + "\n\n[docs/BENCHMARKS.md](docs/BENCHMARKS.md) has every benchmark beside the other simulators.\n\n" + b
            readme.write_text(t[:t.index(a)] + block + t[t.index(b) + len(b):], encoding="utf-8", newline="\n")
            print(f"filled: {readme}")


def main(out: Path, doc: Path | None = None, quiet: bool = False) -> None:
    out = Path(out)
    recs = load(out)
    if not recs:
        raise SystemExit(f"no results in {out}: run a benchmark first")
    made = charts(recs, out / "charts")
    sec = build(recs, "charts", made)
    md = markdown(sec)
    (out / "report.md").write_text(md, encoding="utf-8")
    images = {}
    for c in made:
        base, theme = Path(c).stem.rsplit("_", 1)
        images.setdefault(base, ["", ""])[0 if theme == "light" else 1] = base64.b64encode(Path(c).read_bytes()).decode()
    (out / "report.html").write_text(to_html(md, {k: tuple(v) for k, v in images.items()}), encoding="utf-8")
    if doc:
        fill_doc(Path(doc), sec, out / "charts", made)
    print("\n== at a glance\n" + "\n".join(sec["glance"]) + "\n== summary\n" + "\n".join(sec["summary"]))
    if not quiet:
        print("\n" + "\n".join(sec["speed"]))
    print(f"report: {out / 'report.md'}\n        {out / 'report.html'} (open it in a browser)"
          + "".join(f"\n        {c}" for c in made))
