def pct2(x: float, all_exact: bool) -> str:
    """A percentage to 2 decimals, or 4 above 99.9% (so that a miss never rounds up to 100%)."""
    if all_exact:
        return "100%"
    return f"{x:.4f}%" if x >= 99.9 else f"{x:.2f}%"


def whole_line(sm: dict, r: dict, floats: bool) -> str:
    """The small line under a whole-games cell."""
    ex, n = sm["exact_to_the_end"], sm["recordings"]
    if ex == n:
        return "exact to the end"
    if floats:
        off = sm["compared_rows"] - sm["exact_rows"]
        return (f"{off:,} of {sm['compared_rows']:,} float rows off" if off < 1000 else f"{sm['exact_pct']:.2f}% of float rows exact")
    drifts = sorted(g["first_drift"]["seconds"] for g in r.get("recordings") or []
                    if "error" not in g and g.get("first_drift") and g["first_drift"].get("seconds") is not None)
    k = n - ex
    if ex and drifts and k <= 3:
        return f"{k} match{'es' if k != 1 else ''} drift{'' if k != 1 else 's'}, the first at {drifts[0]:.1f} s"
    return f"first drift after {(sm.get('first_drift_s') or {}).get('median', 0):.1f} s (median)"


def model(recs) -> dict:
    """The accuracy table as cells: per (level, simulator) a dict (v, s, cls), plus the notes under the table."""
    acc = merged_acc(recs)
    cols = COLS + [s for s in sim_sort({k[0] for k in acc}) if s not in COLS]
    levels = [lv for lv in ORDER_LEVELS if any(k[1] == lv for k in acc)]
    notes, cells, counts = [], {}, {}
    flow_who = []                  # the simulators whose whole games ran on the harness's match flow
    for lv in levels:
        peers = [r for k, r in acc.items() if k[1] == lv and r.get("status") == "ok"]
        if lv in WHOLE:
            counts[lv] = max((r["summary"]["recordings"] for r in peers), default=0)
        elif lv != "rlpr":
            counts[lv] = max((r["summary"]["all"]["segments"] for r in peers), default=0)
        for s in cols:
            r = acc.get((s, lv))
            if r is None:
                cells[(lv, s)] = {"v": "not run", "s": "", "cls": "pend"}
                continue
            if r.get("status") == "not supported":
                cells[(lv, s)] = {"v": "—", "s": SHORT_WHY.get(lv) or clean(r.get("why", "")), "cls": "na"}
                continue
            if r.get("status") != "ok":
                cells[(lv, s)] = {"v": r.get("status", "not run"), "s": clean(r.get("why", ""))[:80], "cls": "pend"}
                continue
            who = COL_NAMES.get(s, nice(s))
            if r.get("binding"):
                notes.append(f"{who}'s whole games run through {nice(r['binding'])}, its binding that runs whole matches.")
            if lv in WHOLE:
                sm = r["summary"]
                ex, n = sm["exact_to_the_end"], sm["recordings"]
                small = whole_line(sm, r, lv in ("Cf", "Df"))
                if n < counts[lv]:
                    small += f"; {n} of {counts[lv]} matches"
                cls = "exact" if ex == n else "near" if n > 1 and ex == n - 1 else ""
                cells[(lv, s)] = {"v": f"{ex} / {n}", "s": small, "cls": cls}
                if sm.get("bodies_only") and who not in flow_who:
                    flow_who.append(who)
            elif lv == "rlpr":
                a = r["results"]["segments_120"]["total"]
                cells[(lv, s)] = {"v": f"{a['pass_pct']:.2f}%", "s": f"of car-ticks within tolerance; mean error {a['mean_norm']:.2f}", "cls": ""}
            else:
                a = r["summary"]["all"]
                allx = a["exact_body_ticks"] >= 100.0 and a["exact_segments"] >= 100.0
                small = "of body-ticks exact" if lv == "A" else f"{a['segment_pass']:.2f}% within tolerance"
                most = max(p["summary"]["all"]["body_ticks"] for p in peers)
                recs_most = max(p["summary"]["all"]["recordings"] for p in peers)
                if a["recordings"] < recs_most:
                    # a run on some of the suite's splits: which, and how much of the suite that is
                    sp = sorted(k for k in r["summary"] if k != "all")
                    small += (f"; the {' and '.join(sp)} split{'s' if len(sp) != 1 else ''} only: {a['recordings']} of "
                              f"{recs_most} recordings, {a['body_ticks'] / 1e6:.1f}M of {most / 1e6:.1f}M body-ticks")
                elif a["body_ticks"] < most:
                    small += f"; scored on {a['body_ticks'] / 1e6:.1f}M of {most / 1e6:.1f}M body-ticks"
                    if a.get("failed_segments"):
                        small += f" ({a['failed_segments']:,} segments it couldn't run)"
                cls = "exact" if allx else "near" if a["exact_body_ticks"] >= 99.0 else ""
                cells[(lv, s)] = {"v": pct2(a["exact_body_ticks"], allx), "s": small, "cls": cls}
    if flow_who:
        names = ", ".join(flow_who[:-1]) + (" and " if len(flow_who) > 1 else "") + flow_who[-1]
        one = len(flow_who) == 1
        notes.append(f"Whole games for {names}: the harness supplies the match flow {'it' if one else 'each'} lacks. Every "
                     "kickoff's and respawn's cars are born as the game makes them (the recording's spots through catSim's "
                     "spawn rules from the dump, at the frame the game does it; the simulator runs the drop), each later "
                     "restart puts the ball at the game's own spawn with every boost pad back, and the harness holds the "
                     "cars through each countdown. Each kickoff and respawn puts a new car there with the game's spawn "
                     "boost, 33.3. At float precision the bodies are set to the game's own floats at the first float row "
                     "and at each later kickoff's birth, when they don't already hold them. "
                     f"{'It' if one else 'Each'} runs its own physics, pads, boost and demolitions; scored on bodies only, "
                     "read as the game reads a body for its packets (speeds capped, the rotation through its packed "
                     "quaternion).")
    # which machine ran what, when more than one did
    if any(s == "rocketgpu" and r.get("status") == "ok" and "4070" in " ".join((r.get("machine") or {}).get("gpus") or [])
           for (s, _), r in acc.items()):
        notes.append("RocketGPU (CUDA)'s rows on the RTX 4070 ran with one local build patch that card needs: in CopyCarWorldRow "
                     "(include/rocketgpu/detail/step/env_step.hpp), memcpy(&dst, &src, sizeof(T)) in place of the call with "
                     "__builtin_assume_aligned, which nvcc rejects for sm_89. The same bytes are copied; bench/adapters/rocketgpu.py "
                     "has it.")
    cat_acc = next((r.get("version") for r in acc.values() if r.get("sim") == "catsim" and r.get("version") and r.get("status") == "ok"), "")
    cat_old = sorted({r.get("version", "") for r in recs if r.get("kind") == "speed" and r.get("sim") == "catsim" and r.get("version", "") != cat_acc})
    if cat_acc and cat_old:
        notes.append(f"catSim's speed rows were measured on {cat_old[0].split(' (')[0]}, before the version number moved to "
                     f"{cat_acc.split(' (')[0].split()[-1]}; the only engine change since is where a spawn selector's body is placed, not "
                     "the ticks being timed.")
    speed_cpu = next((r["machine"]["cpu"] for r in recs if r.get("kind") == "speed" and r.get("machine")), None)
    places = {}
    for (sim, lv), r in acc.items():
        if r.get("status") == "ok" and r.get("machine") and r["machine"]["cpu"] != speed_cpu and lv in ROWS:
            places.setdefault(short_machine(r["machine"]), {}).setdefault(lv, set()).add(COL_NAMES.get(sim, nice(sim)))
    for where, rows in places.items():
        bits = [f"{ROWS[lv][0][0].lower()}{ROWS[lv][0][1:]}: {', '.join(sorted(rows[lv]))}" for lv in levels if lv in rows]
        notes.append(f"Accuracy compares bits, so a row doesn't depend on its machine. These ran on {where}, every other row on the "
                     f"machine named above: " + "; ".join(bits) + ".")
    seg_bt = max((r["summary"]["all"]["body_ticks"] for k, r in acc.items() if k[1] in ("A", "B", "Bp") and r.get("status") == "ok"), default=0)
    return {"cols": cols, "levels": levels, "cells": cells, "counts": counts, "notes": list(dict.fromkeys(notes)), "seg_bt": seg_bt}


def groups(m) -> list:
    out = []
    whole = [lv for lv in m["levels"] if lv in WHOLE]
    seg = [lv for lv in m["levels"] if lv not in WHOLE]
    if whole:
        out.append(("Whole games: the simulator runs each match from the first kickoff to the end", whole))
    if seg:
        n = max((m["counts"].get(lv, 0) for lv in seg), default=0)
        out.append((f"Segments: the RocketGPU full-state suite (v2), {n:,} segments of up to 120 ticks, "
                    f"{m['seg_bt'] / 1e6:.1f}M body-ticks", seg))
    return out


